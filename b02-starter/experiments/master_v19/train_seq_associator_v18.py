"""Train & LBFGS-Calibrate V18-C TrackSeqCrossAttnNet on closed-loop DAgger conflict components.

Uses scene-level train/val holdout (last 5 sampled scenes as calibration val split).
"""
import os
os.environ.setdefault("KMP_DUPLICATE_LIB_OK", "TRUE")

import argparse
import pickle
import sys
import time
from pathlib import Path

import numpy as np
import torch
from torch import nn
from torch.nn import functional as F

STARTER_ROOT = Path(__file__).resolve().parents[2]
if str(STARTER_ROOT) not in sys.path:
    sys.path.insert(0, str(STARTER_ROOT))

from b02.master_tracker import TrackSeqCrossAttnNet, SEQ_LEN, SEQ_DIM, EDGE_DIM_V18


def collate_comps(batch):
    bsz = len(batch)
    max_e = max(len(c[0]) for c in batch)
    ef = np.zeros((bsz, max_e, EDGE_DIM_V18), dtype=np.float32)
    es = np.zeros((bsz, max_e, SEQ_LEN, SEQ_DIM), dtype=np.float32)
    rm = np.zeros((bsz, max_e, max_e), dtype=np.int64)
    pm = np.zeros((bsz, max_e), dtype=bool)
    yy = np.full((bsz, max_e), -1.0, dtype=np.float32)
    cf = np.zeros((bsz, max_e), dtype=bool)
    for b, (f16, s16, rel, y, _, is_c) in enumerate(batch):
        e = len(f16)
        ef[b, :e] = f16.astype(np.float32)
        es[b, :e] = s16.astype(np.float32)
        rm[b, :e, :e] = rel.astype(np.int64)
        pm[b, :e] = True
        yy[b, :e] = y
        if is_c:
            cf[b, :e] = True
    return (
        torch.from_numpy(ef), torch.from_numpy(es), torch.from_numpy(rm),
        torch.from_numpy(pm), torch.from_numpy(yy), torch.from_numpy(cf),
    )


def calc_auc_ece(probs: np.ndarray, y: np.ndarray):
    pos = probs[y > 0.5]
    neg = probs[y < 0.5]
    auc = 0.5
    if len(pos) and len(neg):
        all_s = np.concatenate((pos, neg))
        ord_i = np.argsort(all_s)
        ranks = np.empty_like(ord_i, dtype=np.float64)
        ranks[ord_i] = np.arange(1, len(all_s) + 1)
        auc = float((ranks[:len(pos)].sum() - len(pos) * (len(pos) + 1) / 2.0) / (len(pos) * len(neg)))
    bins = np.linspace(0.0, 1.0, 16)
    ece = 0.0
    n = len(y)
    for i in range(15):
        m = (probs >= bins[i]) & (probs < bins[i + 1] if i < 14 else probs <= 1.0)
        if np.any(m):
            ece += (np.sum(m) / n) * abs(float(np.mean(y[m])) - float(np.mean(probs[m])))
    p95_m = probs >= 0.95
    p95 = float(np.mean(y[p95_m])) if np.any(p95_m) else 0.0
    r95 = float(np.sum(y[p95_m]) / max(1.0, np.sum(y)))
    return auc, ece, p95, r95


def main():
    ap = argparse.ArgumentParser(description="Train TrackSeqCrossAttnNet V18-C on DAgger components.")
    ap.add_argument("--data", type=Path, required=True, help="DAgger .pkl generated by collect_dagger_v18.py")
    ap.add_argument("--out", type=Path, required=True, help="Target checkpoint path (.pt)")
    ap.add_argument("--epochs", type=int, default=16)
    ap.add_argument("--batch-size", type=int, default=128)
    ap.add_argument("--device", default="cuda")
    args = ap.parse_args()

    t0 = time.time()
    torch.manual_seed(2026)
    rng = np.random.default_rng(2026)
    device = torch.device(args.device if (args.device == "cuda" and torch.cuda.is_available()) else "cpu")

    with args.data.open("rb") as f:
        data = pickle.load(f)
    comps = data["comps"]
    max_sidx = max(c[4] for c in comps)
    val_start = max(1, max_sidx - 4)
    train_c = [c for c in comps if c[4] < val_start]
    val_c = [c for c in comps if c[4] >= val_start]
    print(f"[V18-SeqAttn] Loaded {len(comps)} comps | train={len(train_c)} | val={len(val_c)}", flush=True)

    model = TrackSeqCrossAttnNet().to(device)
    print(f"[V18-SeqAttn] Params: {sum(p.numel() for p in model.parameters()):,}", flush=True)

    opt = torch.optim.AdamW(model.parameters(), lr=1.5e-3, weight_decay=2e-4)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=args.epochs, eta_min=5e-5)

    best_bce = 1e9
    best_sd = None

    for ep in range(1, args.epochs + 1):
        model.train()
        order = np.argsort([len(c[0]) + rng.uniform(-1.5, 1.5) for c in train_c])
        batches = [order[i:i + args.batch_size] for i in range(0, len(order), args.batch_size)]
        rng.shuffle(batches)

        for b_idx in batches:
            ef, es, rm, pm, yy, cf = collate_comps([train_c[i] for i in b_idx])
            ef = ef.to(device) + torch.randn_like(ef.to(device)) * 0.015
            es, rm, pm, yy, cf = es.to(device), rm.to(device), pm.to(device), yy.to(device), cf.to(device)
            logits = model(ef, es, rm, pm)
            valid = yy >= 0.0
            if not valid.any():
                continue
            wt = torch.ones_like(yy)
            wt = torch.where(cf, wt * 1.35, wt)
            wt = torch.where(yy == 0.0, wt * 1.25, wt)
            bce = F.binary_cross_entropy_with_logits(logits[valid], yy[valid], reduction="none")
            loss = (bce * wt[valid]).sum() / wt[valid].sum().clamp(min=1.0)
            opt.zero_grad(set_to_none=True)
            loss.backward()
            nn.utils.clip_grad_norm_(model.parameters(), 1.5)
            opt.step()
        sched.step()

        if ep % 2 == 0 or ep == args.epochs:
            model.eval()
            v_logits, v_y, v_cf = [], [], []
            with torch.inference_mode():
                for i in range(0, len(val_c), 256):
                    ef, es, rm, pm, yy, cf = collate_comps(val_c[i:i + 256])
                    lg = model(ef.to(device), es.to(device), rm.to(device), pm.to(device)).cpu()
                    m = yy >= 0.0
                    v_logits.append(lg[m]); v_y.append(yy[m]); v_cf.append(cf[m])
            v_lg = torch.cat(v_logits)
            v_yt = torch.cat(v_y)
            v_cfm = torch.cat(v_cf).numpy()
            vbce = float(F.binary_cross_entropy_with_logits(v_lg, v_yt).item())
            vp = torch.sigmoid(v_lg).numpy()
            vy = v_yt.numpy()
            auc, ece, _, _ = calc_auc_ece(vp, vy)
            c_auc, _, c_p95, c_r95 = calc_auc_ece(vp[v_cfm], vy[v_cfm])
            print(f"  ep {ep:2d}/{args.epochs} | val_bce={vbce:.4f} auc={auc:.4f} ECE={ece:.4f} | "
                  f"CONFLICT auc={c_auc:.4f} P@0.95={c_p95:.4f} R@0.95={c_r95:.3f} ({time.time()-t0:.1f}s)", flush=True)
            if vbce < best_bce:
                best_bce = vbce
                best_sd = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}

    model.load_state_dict(best_sd)
    model.eval()
    v_raw, v_y, v_cf = [], [], []
    with torch.inference_mode():
        model.temp.fill_(1.0)
        for i in range(0, len(val_c), 256):
            ef, es, rm, pm, yy, cf = collate_comps(val_c[i:i + 256])
            lg = model(ef.to(device), es.to(device), rm.to(device), pm.to(device)).cpu()
            m = yy >= 0.0
            v_raw.append(lg[m]); v_y.append(yy[m]); v_cf.append(cf[m])
    raw_lg = torch.cat(v_raw).to(device)
    yt = torch.cat(v_y).to(device)
    cfm = torch.cat(v_cf).numpy()

    t_param = nn.Parameter(torch.tensor(1.0, device=device))
    lbfgs = torch.optim.LBFGS([t_param], lr=0.1, max_iter=50)
    def closure():
        lbfgs.zero_grad()
        loss = F.binary_cross_entropy_with_logits(raw_lg / t_param.clamp(0.3, 5.0), yt)
        loss.backward()
        return loss
    lbfgs.step(closure)
    cal_t = float(t_param.clamp(0.3, 5.0).item())
    model.temp.data.fill_(cal_t)

    cal_p = torch.sigmoid(raw_lg / cal_t).detach().cpu().numpy()
    vy = yt.detach().cpu().numpy()
    auc, ece, _, _ = calc_auc_ece(cal_p, vy)
    c_auc, c_ece, c_p95, c_r95 = calc_auc_ece(cal_p[cfm], vy[cfm])
    print(f"[CALIBRATED] temp={cal_t:.4f} | ALL auc={auc:.4f} ECE={ece:.4f} | "
          f"CONFLICT auc={c_auc:.4f} P@0.95={c_p95:.4f} R@0.95={c_r95:.3f} ECE={c_ece:.4f}", flush=True)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    torch.save({
        "state_dict": {k: v.detach().cpu() for k, v in model.state_dict().items()},
        "edge_dim": EDGE_DIM_V18, "seq_len": SEQ_LEN, "seq_dim": SEQ_DIM,
        "cal_temp": cal_t, "val_conflict_auc": c_auc, "val_conflict_ece": c_ece,
    }, args.out)
    print(f"[SAVED] {args.out}", flush=True)


if __name__ == "__main__":
    main()
